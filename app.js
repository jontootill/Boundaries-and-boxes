/* =========================================================================
   2. GAME STATE & VARIABLES
   ========================================================================= */
let selectedIntensity = 'romantic';
let selectedZone = 'all';

const gridBoxes = 4;
const dotsCount = gridBoxes + 1;

let currentPlayer = 1;
let scores = { 1: 0, 2: 0 };

let padding = 30;
let spacing = 80;

let hLines = [];
let vLines = [];
let boxes = [];

let canvas, ctx;

/* =========================================================================
   3. INITIALIZATION & EVENT LISTENERS
   ========================================================================= */
document.addEventListener('DOMContentLoaded', () => {
    setupSingleSelect('intensity-group', (val) => { selectedIntensity = val; });
    setupSingleSelect('zone-group', (val) => { selectedZone = val; });

    const startBtn = document.getElementById('start-game-btn');
    if (startBtn) {
        startBtn.addEventListener('click', startGame);
    }

    const closeBtn = document.getElementById('close-challenge-btn');
    if (closeBtn) {
        closeBtn.addEventListener('click', closeModal);
    }

    canvas = document.getElementById('gameCanvas');
    if (canvas) {
        ctx = canvas.getContext('2d');
        canvas.addEventListener('click', handleCanvasClick);
    }
});

function setupSingleSelect(containerId, callback) {
    const container = document.getElementById(containerId);
    if (!container) return;
    
    const buttons = container.querySelectorAll('.option-btn');
    buttons.forEach(btn => {
        btn.addEventListener('click', () => {
            buttons.forEach(b => b.classList.remove('selected'));
            btn.classList.add('selected');
            callback(btn.getAttribute('data-value'));
        });
    });
}

function startGame() {
    const statusPanel = document.getElementById('game-status-panel');
    if (statusPanel) {
        statusPanel.classList.remove('hidden');
    }
    closeModal();
    initBoard();
    drawBoard();
}

/* =========================================================================
   4. BOARD ENGINE
   ========================================================================= */
function initBoard() {
    spacing = (canvas.width - (padding * 2)) / gridBoxes;
    currentPlayer = 1;
    scores = { 1: 0, 2: 0 };
    updateScoreDisplay();

    hLines = Array(dotsCount).fill(null).map(() => Array(gridBoxes).fill(0));
    vLines = Array(gridBoxes).fill(null).map(() => Array(dotsCount).fill(0));
    boxes = Array(gridBoxes).fill(null).map(() => Array(gridBoxes).fill(0));
}

function drawBoard() {
    ctx.clearRect(0, 0, canvas.width, canvas.height);

    // Captured Boxes
    for (let r = 0; r < gridBoxes; r++) {
        for (let c = 0; c < gridBoxes; c++) {
            if (boxes[r][c] !== 0) {
                ctx.fillStyle = boxes[r][c] === 1 ? 'rgba(76, 201, 240, 0.3)' : 'rgba(247, 37, 133, 0.3)';
                ctx.fillRect(padding + c * spacing, padding + r * spacing, spacing, spacing);
            }
        }
    }

    // Horizontal Lines
    for (let r = 0; r < dotsCount; r++) {
        for (let c = 0; c < gridBoxes; c++) {
            if (hLines[r][c] !== 0) {
                ctx.strokeStyle = hLines[r][c] === 1 ? '#4cc9f0' : '#f72585';
                ctx.lineWidth = 5;
                ctx.beginPath();
                ctx.moveTo(padding + c * spacing, padding + r * spacing);
                ctx.lineTo(padding + (c + 1) * spacing, padding + r * spacing);
                ctx.stroke();
            }
        }
    }

    // Vertical Lines
    for (let r = 0; r < gridBoxes; r++) {
        for (let c = 0; c < dotsCount; c++) {
            if (vLines[r][c] !== 0) {
                ctx.strokeStyle = vLines[r][c] === 1 ? '#4cc9f0' : '#f72585';
                ctx.lineWidth = 5;
                ctx.beginPath();
                ctx.moveTo(padding + c * spacing, padding + r * spacing);
                ctx.lineTo(padding + c * spacing, padding + (r + 1) * spacing);
                ctx.stroke();
            }
        }
    }

    // Dots
    for (let r = 0; r < dotsCount; r++) {
        for (let c = 0; c < dotsCount; c++) {
            ctx.fillStyle = '#f1faee';
            ctx.beginPath();
            ctx.arc(padding + c * spacing, padding + r * spacing, 5, 0, Math.PI * 2);
            ctx.fill();
        }
    }
}

function handleCanvasClick(e) {
    const rect = canvas.getBoundingClientRect();
    const x = e.clientX - rect.left;
    const y = e.clientY - rect.top;
    const clickThreshold = 18;

    // Check Horizontal Lines
    for (let r = 0; r < dotsCount; r++) {
        for (let c = 0; c < gridBoxes; c++) {
            if (hLines[r][c] === 0) {
                let x1 = padding + c * spacing;
                let x2 = padding + (c + 1) * spacing;
                let y1 = padding + r * spacing;

                if (x >= x1 && x <= x2 && Math.abs(y - y1) < clickThreshold) {
                    hLines[r][c] = currentPlayer;
                    processMove();
                    return;
                }
            }
        }
    }

    // Check Vertical Lines
    for (let r = 0; r < gridBoxes; r++) {
        for (let c = 0; c < dotsCount; c++) {
            if (vLines[r][c] === 0) {
                let x1 = padding + c * spacing;
                let y1 = padding + r * spacing;
                let y2 = padding + (r + 1) * spacing;

                if (y >= y1 && y <= y2 && Math.abs(x - x1) < clickThreshold) {
                    vLines[r][c] = currentPlayer;
                    processMove();
                    return;
                }
            }
        }
    }
}

function processMove() {
    let boxCaptured = false;

    for (let r = 0; r < gridBoxes; r++) {
        for (let c = 0; c < gridBoxes; c++) {
            if (boxes[r][c] === 0) {
                if (hLines[r][c] !== 0 && hLines[r+1][c] !== 0 &&
                    vLines[r][c] !== 0 && vLines[r][c+1] !== 0) {
                    
                    boxes[r][c] = currentPlayer;
                    scores[currentPlayer]++;
                    boxCaptured = true;
                }
            }
        }
    }

    drawBoard();
    updateScoreDisplay();

    if (boxCaptured) {
        showChallengeChoices();
    } else {
        currentPlayer = currentPlayer === 1 ? 2 : 1;
        updateScoreDisplay();
    }
}

function updateScoreDisplay() {
    const p1Score = document.getElementById('score-p1');
    const p2Score = document.getElementById('score-p2');
    const turnText = document.getElementById('turn-indicator');

    if (p1Score) p1Score.innerText = scores[1];
    if (p2Score) p2Score.innerText = scores[2];

    if (turnText) {
        turnText.innerHTML = `Current Turn: <strong>Player ${currentPlayer} (${currentPlayer === 1 ? 'Blue' : 'Pink'})</strong>`;
    }
}

